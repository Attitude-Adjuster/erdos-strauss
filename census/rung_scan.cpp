// rung_scan.cpp -- minimal-rung census for the Erdos-Straus hard class p = 1 (mod 24).
// Production build.  Companion code to "A Certificate Hierarchy for Erdos-Straus
// Failures on the Class p = 1 (mod 24)".
//
// For each prime p = 1 (mod 24) in [lo, hi): walk rungs r = 3, 7, 11, ...
// (A = (p+r)/4, q = pA) until some divisor u | q^2 has u = -q (mod r).  Record the
// minimal such r, and classify every FAILED rung by the certificate hierarchy:
//
//   J    the Jacobi symbol (./r) certifies the failure: every prime l | q has
//        (l/r) = +1 while (-q/r) = -1, so no divisor of q^2 can lie in the target
//        class.  Valid for every odd r.  For composite r this is a statement about
//        the SYMBOL, not about quadratic residuosity.
//   RC   some real character mod r certifies, but the Jacobi symbol does not.  For
//        odd r = prod p_i^e_i there are 2^omega(r) real characters -- the products of
//        (./p_i) over subsets -- and Jacobi is only the subset {i : e_i odd}.
//   S    no real character certifies, but -q lies outside the subgroup of (Z/r)*
//        generated by the residues of the primes of q: a higher-order obstruction.
//   R    residual miss: no local certificate at all.
//
//   Nesting J subset RC subset S.  Below 10^5 all three coincide; above they do not.
//
// METHOD.  The scanning core is a bulk sieve-factorization.  Writing p = first + 24j,
// the rung-r denominator is A = (p+r)/4 = A0 + 6j -- an arithmetic progression -- so
// for any prime l >= 5,  l | A  <=>  j = -A0 * 6^{-1} (mod l), again a progression.
// One strided walk per l factors the whole window in O(window * loglog) touches
// instead of pi(B) trial divisions per A.  Because the walk uses every prime up to
// sqrt(Amax), whatever remains of A is PRIME by construction: no primality test and
// no Pollard rho on the main path.  l = 2 and 3 divide all A in a window or none, and
// are stripped directly.  Once the ladder thins below BULK_MIN active primes the
// strided walk stops paying for itself and the tail reverts to per-A factoring.
//
// NO BIGNUM ANYWHERE, to 10^18: p < 2^60 and A < 2^58 fit in u64, and q = pA (~10^35)
// is never formed -- only q mod r, as (p%r)(A%r)%r.  Rung arithmetic is on residues
// below r <= 255.
//
// OPERATIONAL NOTES
//  * Run --verify on every distinct machine and compiler BEFORE trusting output.
//  * Do NOT rebuild the binary while a run is in flight: the linker rewrites the file
//    in place and the running process dies.  run8.sh copies the binary first.
//  * Emitted lines are streamed per window and are therefore NOT sorted; merge.py
//    sorts and checks shard coverage.
//
// BUILD   make            TEST  make check          RUN   ./run8.sh LO HI
// Public domain / CC0.  No warranty.

